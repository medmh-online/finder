'use strict';
const assert=require('node:assert/strict');
const {messageIdOf,eventIdOf,outgoingMediaEchoMatches}=require('./message_events');
const target='212612345678@c.us';
assert.equal(messageIdOf({id:{_serialized:'true_212612345678@c.us_X'}}),'true_212612345678@c.us_X');
assert.equal(messageIdOf({id:{$1:'true_212612345678@c.us_X'}}),'true_212612345678@c.us_X');
assert.equal(messageIdOf({id:{id:'3A1111111111',remote:target,fromMe:true}}),`true_${target}_3A1111111111`);
assert.equal(messageIdOf({id:{id:'AB'}}),null);
const first={id:{$1:'false_212612345678@c.us_AAA'},from:target,fromMe:false,timestamp:77,body:'salam'};
assert.equal(eventIdOf(first,target,'in'),eventIdOf(first,target,'in'));
assert.equal(eventIdOf({id:{_serialized:'false_212612345678@c.us_AAA'}},target,'in'),eventIdOf(first,target,'in'));
const withoutId={from:target,fromMe:false,timestamp:77,body:'salam'};
assert.equal(eventIdOf(withoutId,target,'in'),eventIdOf({...withoutId},target,'in'));
assert.notEqual(eventIdOf(withoutId,target,'in'),eventIdOf({...withoutId,body:'hello'},target,'in'));
const doc={fromMe:true,to:target,id:{$1:'true_212612345678@c.us_DOC'},type:'document',hasMedia:true,body:'random.pdf'};
assert.equal(outgoingMediaEchoMatches(doc,target,'document','Voici votre CV',true),true);
assert.equal(outgoingMediaEchoMatches({...doc,to:'212600000000@c.us'},target,'document','CV',true),false);
assert.equal(outgoingMediaEchoMatches({...doc,type:'chat',hasMedia:false},target,'document','CV',true),false);
assert.equal(outgoingMediaEchoMatches({...doc,id:{}},target,'document','CV',true),false);
const text={fromMe:true,to:target,id:{$1:'true_212612345678@c.us_TXT'},type:'chat',body:'salut',hasMedia:false};
assert.equal(outgoingMediaEchoMatches(text,target,null,'salut',false),true);
assert.equal(outgoingMediaEchoMatches(text,target,null,'hey',false),false);
console.log('Message event and media receipt tests passed');
